// Generates the service worker (dist/sw.js) and offline manifest (dist/offline.json) after `vite build`.
//
// Caches:
//   medibible-shell-<version>  page, scripts, styles, icons: replaced as a whole on each new version
//   medibible-data             data files, each stored under "<url>?v=<content hash>", so unchanged files
//                              survive new deploys and an older app never reads newer data
// Precached on install: the shell plus the data the first screen needs (bible, xrefs, links).
// Everything else under data/ is cached when first used, or all at once via About -> Offline.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { gzipSync } from 'node:zlib';
import { root } from './lib/stepbible.mjs';

const dist = join(root, 'dist');
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else files.push(relative(dist, full).split(sep).join('/'));
  }
})(dist);

const CORE_DATA = ['data/bible.json', 'data/xrefs.json', 'data/links.json'];
const hashOf = (p) => createHash('sha256').update(readFileSync(join(dist, p))).digest('hex').slice(0, 16);
const excluded = new Set(['sw.js', 'offline.json']);

const shell = files.filter((p) => !p.startsWith('data/') && !excluded.has(p)).sort();
const data = files.filter((p) => p.startsWith('data/')).sort();
const hashes = Object.fromEntries(data.map((p) => [p, hashOf(p)]));
const version = createHash('sha256')
  .update(shell.map((p) => `${p}:${hashOf(p)}`).join('\n'))
  .update(JSON.stringify(hashes))
  .digest('hex').slice(0, 12);

const optional = data.filter((p) => !CORE_DATA.includes(p)).map((p) => {
  const body = readFileSync(join(dist, p));
  return { path: p, hash: hashes[p], bytes: body.length, gzip: gzipSync(body, { level: 6 }).length };
});

writeFileSync(join(dist, 'offline.json'), JSON.stringify({ version, dataCache: 'medibible-data', core: CORE_DATA, optional }));

const sw = `// MediBible service worker – generated by scripts/build-sw.mjs. Do not edit dist/sw.js by hand.
const VERSION = ${JSON.stringify(version)};
const SHELL_CACHE = 'medibible-shell-' + VERSION;
const DATA_CACHE = 'medibible-data';
const SHELL = ${JSON.stringify(shell)};
const CORE_DATA = ${JSON.stringify(CORE_DATA)};
const HASHES = ${JSON.stringify(hashes)};

const scope = () => self.registration.scope;
const url = (p) => new URL(p, scope()).href;
const pathOf = (href) => {
  const u = new URL(href);
  return u.href.startsWith(scope()) ? decodeURIComponent(u.pathname.slice(new URL(scope()).pathname.length)) : null;
};
const dataKey = (p) => url(p) + '?v=' + HASHES[p];

async function sha16(buffer) {
  const d = await crypto.subtle.digest('SHA-256', buffer);
  return [...new Uint8Array(d)].map((b) => b.toString(16).padStart(2, '0')).join('').slice(0, 16);
}

/** Fetches a data file, checks it is the version this app expects, and stores it. */
async function fetchData(p) {
  const res = await fetch(url(p), { cache: 'no-cache' });
  if (!res.ok) return res;
  const body = await res.clone().arrayBuffer();
  if ((await sha16(body)) === HASHES[p]) {
    await (await caches.open(DATA_CACHE)).put(dataKey(p), res.clone());
  } else {
    // The server has newer data than this app version: use it now, don't keep it, and look for an update.
    self.registration.update();
  }
  return res;
}

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const shell = await caches.open(SHELL_CACHE);
    await shell.addAll(SHELL.map((p) => new Request(url(p), { cache: 'no-cache' })));
    const data = await caches.open(DATA_CACHE);
    for (const p of CORE_DATA) {
      if (!(await data.match(dataKey(p)))) {
        const res = await fetchData(p);
        if (!res.ok) throw new Error('could not precache ' + p);
      }
    }
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith('medibible-shell-') && name !== SHELL_CACHE) await caches.delete(name);
    }
    // Drop data saved for other versions; files whose content is unchanged keep their entries.
    const data = await caches.open(DATA_CACHE);
    const wanted = new Set(Object.keys(HASHES).map(dataKey));
    for (const req of await data.keys()) if (!wanted.has(req.url)) await data.delete(req);
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const p = pathOf(req.url);
  if (p === null) return; // other sites: not ours

  if (req.mode === 'navigate') {
    event.respondWith((async () => (await caches.match(url('index.html'), { cacheName: SHELL_CACHE })) || fetch(req))());
    return;
  }
  if (p in HASHES) {
    event.respondWith((async () => (await caches.match(dataKey(p), { cacheName: DATA_CACHE })) || fetchData(p))());
    return;
  }
  if (SHELL.includes(p)) {
    event.respondWith((async () => (await caches.match(url(p), { cacheName: SHELL_CACHE })) || fetch(req))());
  }
});
`;
writeFileSync(join(dist, 'sw.js'), sw);

const mb = (n) => (n / 1048576).toFixed(1);
const coreGz = CORE_DATA.reduce((s, p) => s + gzipSync(readFileSync(join(dist, p)), { level: 6 }).length, 0);
console.log(`service worker ${version}: shell ${shell.length} files, core data ${mb(coreGz)} MB, optional ${optional.length} files ${mb(optional.reduce((s, f) => s + f.gzip, 0))} MB (compressed)`);
